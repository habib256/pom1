#!/usr/bin/env python3
"""Generate dev/lib/sid/sid_notes.inc — 96-note SID frequency table.

The SID frequency formula at the Apple-1's 1.022727 MHz CPU clock:
    sid_value = round(freq_hz * 2^24 / CPU_CLOCK_HZ)

Notes are numbered MIDI-style: index 0 = C0 (16.35 Hz), index 95 = B7
(3951 Hz). 12 notes per octave, equal-temperament tuning anchored at
A4 = 440 Hz (index 57).

Tables emitted:
    sid_notes_lo[96] -- low byte of each 16-bit SID frequency value
    sid_notes_hi[96] -- high byte
    NOTE_<NAME><OCTAVE> -- equate per note (NOTE_CS4 = 49, etc.)

Second table, `--top-octave` (dev/lib/sid/sid_notes12.inc): the 12 notes of
octave 7 only. sid_player.asm's default build derives every other octave
from it by shifting right once per octave down, rounding on the last bit
shifted out -- 24 bytes instead of 192 (the pom2games edition's AYS player
does the same with its 12-note period table, AYSONG_FAST_PERIODS being its
opt-in for the full one). The file carries one ca65 .assert per (note,
shift) proving that rounding never carries into the high byte, so the
player's single `INC lo` is exact; and this generator reports how far the
shifted values stray from the 96-note table (5 notes of 96, by 1 LSB each).

Run:
    python3 tools/build_sid_notes.py > dev/lib/sid/sid_notes.inc
    python3 tools/build_sid_notes.py --top-octave > dev/lib/sid/sid_notes12.inc
    python3 tools/build_sid_notes.py --check     # both files up to date?
"""
import io
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

CPU_CLOCK_HZ = 1_022_727
TWO_24 = 1 << 24
NOTE_NAMES = ['C', 'CS', 'D', 'DS', 'E', 'F', 'FS', 'G', 'GS', 'A', 'AS', 'B']


def freq_for_index(n: int) -> float:
    """Return MIDI-style frequency in Hz for note index n (0=C0, 57=A4)."""
    return 440.0 * (2 ** ((n - 57) / 12.0))


def sid_value(freq_hz: float) -> int:
    val = round(freq_hz * TWO_24 / CPU_CLOCK_HZ)
    return min(val, 65535)


def shifted(top: int, shift: int) -> int:
    """sid_player.asm's derivation: shift right, round on the last bit out."""
    if shift == 0:
        return top
    return (top >> shift) + ((top >> (shift - 1)) & 1)


def emit_full(out) -> None:
    notes = [sid_value(freq_for_index(n)) for n in range(96)]

    out.write(';' + '=' * 76 + '\n')
    out.write('; sid_notes.inc -- 96-note frequency table (C0..B7) for SID at 1.022727 MHz\n')
    out.write(';' + '=' * 76 + '\n')
    out.write('; Generated by tools/build_sid_notes.py — do not edit by hand.\n')
    out.write('; Index 0 = C0 (16.35 Hz), index 95 = B7 (3951 Hz). 12 notes per octave,\n')
    out.write('; standard equal-temperament tuning (A4 = 440 Hz at index 57).\n')
    out.write(';\n')
    out.write('; SID register format: 16-bit frequency value, lo byte at $C800/$C807/$C80E\n')
    out.write('; (per voice), hi byte at +1. Computed as:\n')
    out.write(';   sid_value = round(freq_hz * 2^24 / CPU_CLOCK_HZ)\n')
    out.write('; where CPU_CLOCK_HZ = 1 022 727 (real Apple-1 clock; same in POM1).\n')
    out.write(';' + '=' * 76 + '\n\n')

    for table_name, shift in (('sid_notes_lo', 0), ('sid_notes_hi', 8)):
        out.write(f'{table_name}:\n')
        for octave in range(8):
            row = [f'${(notes[octave * 12 + s] >> shift) & 0xFF:02X}'
                   for s in range(12)]
            out.write(f"        .byte   {', '.join(row)}    ; octave {octave}\n")
        out.write('\n')

    out.write('; --- Note index equates (MIDI-style numbering from C0 = 0) ------------------\n')
    for n in range(96):
        octave = n // 12
        name = NOTE_NAMES[n % 12]
        out.write(f'NOTE_{name}{octave} = {n}\n')


def emit_top_octave(out) -> None:
    notes = [sid_value(freq_for_index(n)) for n in range(96)]
    top = notes[84:96]
    out.write(';' + '=' * 76 + '\n')
    out.write('; sid_notes12.inc -- octave-7 SID frequency table (C7..B7), 12 notes\n')
    out.write(';' + '=' * 76 + '\n')
    out.write('; Generated by tools/build_sid_notes.py --top-octave — do not edit by hand.\n')
    out.write('; sid_player.asm (default build) plays note n as\n')
    out.write(';   value = top[n mod 12] >> s, rounded on the last bit shifted out,\n')
    out.write(';   s = 7 - n div 12\n')
    out.write('; Same formula as sid_notes.inc for octave 7; below it, 5 of the 84 derived\n')
    out.write('; values differ from the directly rounded ones by 1 LSB (< 0.1 cent).\n')
    out.write('; Worst pitch error against equal temperament, all 96 notes: ')
    out.write(f'{worst_cents(lambda n: shifted(top[n % 12], 7 - n // 12)):.2f} cents\n')
    out.write(f'; (the 96-note table: {worst_cents(lambda n: notes[n]):.2f} cents).\n')
    out.write(';' + '=' * 76 + '\n\n')
    for i, v in enumerate(top):
        out.write(f'SID_TOP_{i} = ${v:04X}    ; {NOTE_NAMES[i]}7\n')
    names = ', '.join(f'SID_TOP_{i}' for i in range(12))
    out.write(f'\nsid_top_lo:\n        .lobytes {names}\n')
    out.write(f'sid_top_hi:\n        .hibytes {names}\n')
    out.write('\n; Rounding never carries: after a shift of k (1..7) the low byte and the bit\n')
    out.write('; shifted out are never all ones, so `INC lo` alone completes the round.\n')
    out.write('.repeat 12, N\n.repeat 7, K\n')
    out.write('.assert ((.ident(.sprintf("SID_TOP_%d", N)) >> K) .bitand $1FF) <> $1FF, '
              'error, "sid_notes12: rounding would carry into the high byte"\n')
    out.write('.endrepeat\n.endrepeat\n')
    for v in top:                    # the same proof, here, so a bad table never gets written
        for k in range(7):
            assert ((v >> k) & 0x1FF) != 0x1FF


def worst_cents(value_of) -> float:
    worst = 0.0
    for n in range(96):
        ideal = freq_for_index(n) * TWO_24 / CPU_CLOCK_HZ
        worst = max(worst, abs(1200 * math.log2(value_of(n) / ideal)))
    return worst


TARGETS = (('dev/lib/sid/sid_notes.inc', emit_full),
           ('dev/lib/sid/sid_notes12.inc', emit_top_octave))


def main() -> int:
    if '--check' in sys.argv[1:]:
        stale = []
        for rel, emit in TARGETS:
            buf = io.StringIO()
            emit(buf)
            if (ROOT / rel).read_text() != buf.getvalue():
                stale.append(rel)
        for rel in stale:
            print(f'STALE {rel}: rerun tools/build_sid_notes.py')
        return 1 if stale else 0
    emit = emit_top_octave if '--top-octave' in sys.argv[1:] else emit_full
    emit(sys.stdout)
    return 0


if __name__ == '__main__':
    sys.exit(main())
