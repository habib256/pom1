#!/usr/bin/env python3
# ============================================================================
# build_charmap_tms.py -- emit dev/lib/tms9918/charmap_tms.inc from the
# Apple-1 character ROM roms/charmap.rom, bit-reversed for the TMS9918.
# ----------------------------------------------------------------------------
# The Apple-1 character ROM stores each glyph row with bit 0 = leftmost pixel;
# the TMS9918 pattern table reads bit 7 = leftmost pixel. tms9918_text.asm
# (upload_charmap) and text_bitmap.asm (text_blit_glyph) used to .incbin the
# ROM and bit-reverse every byte at run time (8 LSR/ROL rounds a byte, about
# 120 cycles; upload_charmap paid ~165 000 cycles for the 1 KB font). This
# tool does the reversal once, at build time, so both routines copy bytes
# straight to VRAM.
#
# Same glyphs, same look: 128 glyphs (codes $00-$7F, indexed code*8), 8 bytes
# a glyph, byte = reverse_bits(charmap.rom byte). Not the C64 or Beautiful
# Boot fonts -- the Apple-1's own character set.
#
# `--check` (wired into `make -C dev/lib check`) fails when the committed
# .inc no longer matches the ROM.
# ============================================================================
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "roms" / "charmap.rom"
OUT = ROOT / "dev" / "lib" / "tms9918" / "charmap_tms.inc"

GLYPH_COUNT = 128
BYTES_PER_GLYPH = 8


def reverse_bits(b):
    return int(f"{b:08b}"[::-1], 2)


def load_rom():
    raw = SRC.read_bytes()
    if len(raw) != GLYPH_COUNT * BYTES_PER_GLYPH:
        sys.exit(f"{SRC}: expected {GLYPH_COUNT * BYTES_PER_GLYPH} bytes, "
                 f"got {len(raw)}")
    return raw


def label(code):
    if 0x20 <= code < 0x7F and code not in (0x27, 0x3B):
        return f"'{chr(code)}'"
    return ""


def render(raw):
    lines = [
        "; ============================================================================",
        "; charmap_tms.inc -- Apple-1 character ROM, TMS9918 pattern encoding.",
        "; GENERATED by tools/build_charmap_tms.py from roms/charmap.rom.",
        "; DO NOT EDIT -- rerun the tool after changing the ROM.",
        "; ----------------------------------------------------------------------------",
        "; 128 glyphs (codes $00-$7F, index code*8), 8 bytes a glyph, MSB = leftmost",
        "; pixel: every byte is the bit-reverse of the ROM byte (the Apple-1 ROM keeps",
        "; bit 0 = leftmost). Text Mode F1 shows pattern bits 7..2, i.e. ROM bits 0..5.",
        ";",
        "; Inline data fragment (no .export, no guard): `.include` it where the table",
        "; must live and address it through the `tms_charmap` label. Consumers:",
        "; tms9918_text.asm (upload_charmap), text_bitmap.asm (text_blit_glyph).",
        "; cc65 include path: dev/lib/tms9918/.",
        "; ============================================================================",
        "",
        f"TMS_CHARMAP_GLYPH_COUNT     = {GLYPH_COUNT}",
        f"TMS_CHARMAP_BYTES_PER_GLYPH = {BYTES_PER_GLYPH}",
        "",
        "tms_charmap:",
    ]
    for code in range(GLYPH_COUNT):
        glyph = raw[code * BYTES_PER_GLYPH:(code + 1) * BYTES_PER_GLYPH]
        data = ",".join(f"${reverse_bits(b):02X}" for b in glyph)
        tag = label(code)
        lines.append(f"        .byte {data} ; ${code:02X}{' ' + tag if tag else ''}")
    return "\n".join(lines) + "\n"


def main(argv):
    p = argparse.ArgumentParser(
        description="Emit the bit-reversed Apple-1 charmap for the TMS9918.")
    p.add_argument("--check", action="store_true",
                   help="diff regenerated output against the on-disk .inc "
                        "(exit 1 on drift); writes nothing")
    args = p.parse_args(argv)

    new = render(load_rom())
    rel = OUT.relative_to(ROOT)
    if args.check:
        old = OUT.read_text() if OUT.exists() else ""
        if old != new:
            print(f"[diff] {rel} differs from roms/charmap.rom -- rerun "
                  f"tools/build_charmap_tms.py", file=sys.stderr)
            return 1
        print(f"[ok]   {rel}", file=sys.stderr)
        return 0
    OUT.write_text(new)
    print(f"wrote {rel} ({GLYPH_COUNT} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
